"""Object storage for original uploaded files.

``S3ObjectStorage`` talks to any S3-compatible service (development: RustFS from
docker-compose.yml; production: AWS S3 or similar). ``LocalObjectStorage`` keeps
files in a directory. Keys are generated by the application, never taken from
user input, so they can't escape their prefix.
"""

import logging
from collections.abc import Callable
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from anyio import to_thread

from app.core.config import settings

logger = logging.getLogger(__name__)


class StorageError(Exception):
    """Object storage is unreachable or refused the operation."""


class ObjectStorage(Protocol):
    async def put(self, key: str, data: bytes, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None:
        """Remove an object; succeeds if it doesn't exist."""
        ...

    async def list_keys(self, prefix: str) -> list[str]: ...


class S3ObjectStorage:
    def __init__(
        self,
        *,
        bucket: str,
        endpoint_url: str | None,
        access_key_id: str,
        secret_access_key: str,
        region: str,
    ) -> None:
        import boto3
        from botocore.config import Config

        self.bucket = bucket
        self._client = boto3.client(
            "s3",
            endpoint_url=endpoint_url,
            aws_access_key_id=access_key_id,
            aws_secret_access_key=secret_access_key,
            region_name=region,
            config=Config(
                s3={"addressing_style": "path"},  # what S3-compatible servers expect
                retries={"max_attempts": 3, "mode": "standard"},
                connect_timeout=5,
                read_timeout=30,
            ),
        )
        self._bucket_ready = False

    def _ensure_bucket(self) -> None:
        if self._bucket_ready:
            return
        from botocore.exceptions import ClientError

        try:
            self._client.head_bucket(Bucket=self.bucket)
        except ClientError:
            # Development convenience; in production the bucket is provisioned.
            self._client.create_bucket(Bucket=self.bucket)
        self._bucket_ready = True

    async def _run[T](self, fn: Callable[[], T]) -> T:
        """Run a blocking boto3 call in a worker thread; normalize its errors."""
        from botocore.exceptions import BotoCoreError, ClientError

        try:
            return await to_thread.run_sync(fn)
        except (BotoCoreError, ClientError) as exc:
            raise StorageError(str(exc)) from exc

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        def _put() -> None:
            self._ensure_bucket()
            self._client.put_object(
                Bucket=self.bucket, Key=key, Body=data, ContentType=content_type
            )

        await self._run(_put)

    async def get(self, key: str) -> bytes:
        def _get() -> bytes:
            return self._client.get_object(Bucket=self.bucket, Key=key)["Body"].read()

        return await self._run(_get)

    async def delete(self, key: str) -> None:
        await self._run(lambda: self._client.delete_object(Bucket=self.bucket, Key=key))

    async def list_keys(self, prefix: str) -> list[str]:
        def _list() -> list[str]:
            self._ensure_bucket()
            keys: list[str] = []
            for page in self._client.get_paginator("list_objects_v2").paginate(
                Bucket=self.bucket, Prefix=prefix
            ):
                keys.extend(item["Key"] for item in page.get("Contents", []))
            return keys

        return await self._run(_list)


class LocalObjectStorage:
    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):  # defense in depth: keys are generated
            raise StorageError(f"Invalid storage key: {key!r}")
        return path

    async def put(self, key: str, data: bytes, content_type: str) -> None:
        def _put() -> None:
            path = self._path(key)
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)

        await to_thread.run_sync(_put)

    async def get(self, key: str) -> bytes:
        try:
            return await to_thread.run_sync(self._path(key).read_bytes)
        except FileNotFoundError as exc:
            raise StorageError(f"No such object: {key}") from exc

    async def delete(self, key: str) -> None:
        await to_thread.run_sync(lambda: self._path(key).unlink(missing_ok=True))

    async def list_keys(self, prefix: str) -> list[str]:
        def _list() -> list[str]:
            base = self._path(prefix.rstrip("/")) if prefix else self.root
            if not base.exists():
                return []
            return sorted(
                path.relative_to(self.root).as_posix() for path in base.rglob("*") if path.is_file()
            )

        return await to_thread.run_sync(_list)


@lru_cache
def get_object_storage() -> ObjectStorage:
    if settings.storage_backend == "local":
        return LocalObjectStorage(settings.local_storage_dir)
    return S3ObjectStorage(
        bucket=settings.s3_bucket,
        endpoint_url=settings.s3_endpoint_url,
        access_key_id=settings.s3_access_key_id,
        secret_access_key=settings.s3_secret_access_key.get_secret_value(),
        region=settings.s3_region,
    )
