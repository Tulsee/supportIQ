import enum
import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    Computed,
    DateTime,
    ForeignKey,
    Identity,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    false,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base, TimestampMixin, UUIDPrimaryKeyMixin, str_enum_type
from app.models.customer import Customer
from app.models.user import User

# Full-text search configuration for subjects and message bodies.
SEARCH_CONFIG = "english"


class TicketStatus(enum.StrEnum):
    OPEN = "open"
    ASSIGNED = "assigned"
    IN_PROGRESS = "in_progress"
    WAITING_FOR_CUSTOMER = "waiting_for_customer"
    RESOLVED = "resolved"
    CLOSED = "closed"


class TicketPriority(enum.StrEnum):
    LOW = "low"
    NORMAL = "normal"
    HIGH = "high"
    URGENT = "urgent"


class MessageAuthorType(enum.StrEnum):
    AGENT = "agent"  # admin or agent of the organization
    CUSTOMER = "customer"


class TicketEventType(enum.StrEnum):
    CREATED = "created"
    STATUS_CHANGED = "status_changed"
    PRIORITY_CHANGED = "priority_changed"
    SUBJECT_CHANGED = "subject_changed"
    ASSIGNED = "assigned"
    UNASSIGNED = "unassigned"


# Events a customer may see on their own tickets (also enforced by RLS).
CUSTOMER_VISIBLE_EVENTS = (TicketEventType.CREATED, TicketEventType.STATUS_CHANGED)


def _insertion_order() -> Mapped[int]:
    """Position in insertion order. Conversations and timelines sort by this, not by
    created_at: rows written in one transaction share its now(), e.g. the
    "assigned" and "status_changed" events of a single update."""
    return mapped_column(BigInteger, Identity(always=True))


def _search_vector(column: str) -> Mapped[str]:
    # Generated by Postgres; never loaded by the ORM (only queried against).
    return mapped_column(
        TSVECTOR,
        Computed(f"to_tsvector('{SEARCH_CONFIG}'::regconfig, {column})", persisted=True),
        deferred=True,
        deferred_raiseload=True,
    )


class TicketCounter(Base):
    """Per-organization ticket numbers (#1, #2, ...), allocated atomically."""

    __tablename__ = "ticket_counters"

    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE"), primary_key=True
    )
    last_number: Mapped[int] = mapped_column(Integer)


class Ticket(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    __tablename__ = "tickets"
    __table_args__ = (
        UniqueConstraint("organization_id", "number"),
        Index("ix_tickets_organization_id_updated_at", "organization_id", "updated_at"),
        Index("ix_tickets_organization_id_status", "organization_id", "status"),
        Index("ix_tickets_search_vector", "search_vector", postgresql_using="gin"),
    )

    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE")
    )
    number: Mapped[int] = mapped_column(Integer)
    # RESTRICT: a customer with tickets can't be deleted (history must survive).
    customer_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("customers.id", ondelete="RESTRICT"), index=True
    )
    subject: Mapped[str] = mapped_column(String(300))
    status: Mapped[TicketStatus] = mapped_column(
        str_enum_type(TicketStatus, "ticket_status"),
        default=TicketStatus.OPEN,
        server_default=TicketStatus.OPEN.value,
    )
    priority: Mapped[TicketPriority] = mapped_column(
        str_enum_type(TicketPriority, "ticket_priority"),
        default=TicketPriority.NORMAL,
        server_default=TicketPriority.NORMAL.value,
    )
    assignee_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), index=True
    )
    created_by_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL")
    )
    resolved_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    closed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    search_vector: Mapped[str] = _search_vector("subject")

    customer: Mapped[Customer] = relationship(lazy="raise")
    assignee: Mapped[User | None] = relationship(foreign_keys=[assignee_id], lazy="raise")


class TicketMessage(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    """A reply on a ticket, or an internal note (``is_internal``) that customers
    never see."""

    __tablename__ = "ticket_messages"
    __table_args__ = (
        Index("ix_ticket_messages_ticket_id_seq", "ticket_id", "seq"),
        Index("ix_ticket_messages_search_vector", "search_vector", postgresql_using="gin"),
    )

    seq: Mapped[int] = _insertion_order()

    # Denormalized from the ticket so row-level security can check it directly.
    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE")
    )
    ticket_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("tickets.id", ondelete="CASCADE"))
    author_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    author_type: Mapped[MessageAuthorType] = mapped_column(
        str_enum_type(MessageAuthorType, "message_author_type")
    )
    body: Mapped[str] = mapped_column(Text)
    is_internal: Mapped[bool] = mapped_column(default=False, server_default=false())
    search_vector: Mapped[str] = _search_vector("body")

    # Also tells the unit of work to insert a new ticket before its first message.
    ticket: Mapped[Ticket] = relationship(lazy="raise")
    author: Mapped[User | None] = relationship(lazy="raise")


class TicketEvent(UUIDPrimaryKeyMixin, Base):
    """An entry in a ticket's timeline (status, priority, assignment changes).

    ``data`` snapshots what changed, e.g. ``{"from": "open", "to": "assigned"}``;
    assignment events store ``{"id", "name"}`` of the people involved, as they were.
    """

    __tablename__ = "ticket_events"
    __table_args__ = (Index("ix_ticket_events_ticket_id_seq", "ticket_id", "seq"),)

    seq: Mapped[int] = _insertion_order()
    organization_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("organizations.id", ondelete="CASCADE")
    )
    ticket_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("tickets.id", ondelete="CASCADE"))
    actor_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    type: Mapped[TicketEventType] = mapped_column(
        str_enum_type(TicketEventType, "ticket_event_type")
    )
    data: Mapped[dict[str, Any]] = mapped_column(
        JSONB, default=dict, server_default=text("'{}'::jsonb")
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )

    ticket: Mapped[Ticket] = relationship(lazy="raise")
    actor: Mapped[User | None] = relationship(lazy="raise")
